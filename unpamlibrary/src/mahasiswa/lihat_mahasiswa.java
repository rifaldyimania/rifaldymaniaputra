   private void loadDataMahasiswa() {
    DefaultTableModel modelLoad = new DefaultTableModel(new String[]{"NAMA", "NIM", "JURUSAN", "ANGKATAN"}, 0);
    try {
        Connection conn = koneksi.getConnection(); 
        Statement stm = conn.createStatement();
        ResultSet res = stm.executeQuery("SELECT * FROM mahasiswa");

        while (res.next()) {
            modelLoad.addRow(new Object[]{
                res.getString("nama"),
                res.getString("nim"),
                res.getString("jurusan"),
                res.getString("angkatan")
            });
        }
        jTable1.setModel(modelLoad);
    } catch (Exception e) {
        // Biar kelihatan error aslinya apa, bukan cuma "Not supported yet"
        JOptionPane.showMessageDialog(this, "Error load data: " + e.toString());
    }
}
