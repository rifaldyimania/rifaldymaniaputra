    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        String keyword = jTextField1.getText().trim();
    DefaultTableModel modelSearch = new DefaultTableModel(new String[]{"NAMA", "NIM", "JURUSAN", "ANGKATAN"}, 0);
    
    try {
        Connection conn = koneksi.getConnection(); // Pastikan pemanggilan koneksi benar
        String sql = "SELECT * FROM mahasiswa WHERE nama LIKE ? OR nim LIKE ?";
        PreparedStatement pst = conn.prepareStatement(sql);
        pst.setString(1, "%" + keyword + "%");
        pst.setString(2, "%" + keyword + "%");
        ResultSet res = pst.executeQuery();

        while (res.next()) {
            modelSearch.addRow(new Object[]{
                res.getString("nama"),
                res.getString("nim"),
                res.getString("jurusan"),
                res.getString("angkatan")
            });
        }
        jTable1.setModel(modelSearch);
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error saat mencari data: " + e.getMessage());
    }
    }//GEN-LAST:event_jButton1ActionPerformed

